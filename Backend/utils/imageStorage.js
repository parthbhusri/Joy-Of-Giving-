// Stores the photo of each scanned toy and hands it back later.
//
// - On Cloud Run (GCS_BUCKET is set): photos go into a Google Cloud Storage
//   bucket. Cloud Run authenticates automatically with its service account,
//   so no keys are needed in the code.
// - On a developer laptop (GCS_BUCKET not set): photos go into Backend/uploads/.
//
// Either way the database only stores a short "key" (e.g. toy-images/<id>.jpg),
// so the rest of the app doesn't care where the file actually lives.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { Storage } from '@google-cloud/storage'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const LOCAL_DIR = path.join(__dirname, '..', 'uploads')

// Only these types are stored (and later served back). Anything else, such
// as SVG, could carry scripts, so it is never saved.
const EXTENSIONS = {
  'image/jpeg': 'jpg',
  'image/png': 'png',
  'image/webp': 'webp',
  'image/heic': 'heic',
  'image/heif': 'heif',
  'image/gif': 'gif'
}

let bucket = null

function getBucket() {
  if (!bucket) {
    bucket = new Storage().bucket(process.env.GCS_BUCKET)
  }

  return bucket
}

const useCloud = () => Boolean(process.env.GCS_BUCKET)

export function describeStorage() {
  return useCloud()
    ? `Google Cloud Storage bucket "${process.env.GCS_BUCKET}"`
    : `local folder ${LOCAL_DIR}`
}

export function isStorableImage(mimeType) {
  return Object.hasOwn(EXTENSIONS, mimeType)
}

// Keys are generated by us (UUID + fixed extension), never taken from the
// upload, and are re-checked here so a bad key can't escape the uploads folder.
function assertSafeKey(key) {
  if (!/^toy-images\/[A-Za-z0-9-]+\.[a-z0-9]+$/.test(key)) {
    throw new Error('Invalid image key')
  }
}

export async function saveImage({ publicId, buffer, mimeType }) {
  if (!isStorableImage(mimeType)) {
    throw new Error(`Unsupported image type: ${mimeType}`)
  }

  const key = `toy-images/${publicId}.${EXTENSIONS[mimeType]}`

  assertSafeKey(key)

  if (useCloud()) {
    await getBucket().file(key).save(buffer, {
      contentType: mimeType,
      resumable: false
    })
  } else {
    const filePath = path.join(LOCAL_DIR, key)

    await fs.promises.mkdir(path.dirname(filePath), { recursive: true })
    await fs.promises.writeFile(filePath, buffer)
  }

  return { imageKey: key, imageMimeType: mimeType }
}

// Returns a readable stream of the stored photo.
export function openImage(key) {
  assertSafeKey(key)

  return useCloud()
    ? getBucket().file(key).createReadStream()
    : fs.createReadStream(path.join(LOCAL_DIR, key))
}

// Best-effort cleanup (used when the database save fails after the photo
// was stored). Never throws.
export async function deleteImage(key) {
  try {
    assertSafeKey(key)

    if (useCloud()) {
      await getBucket().file(key).delete({ ignoreNotFound: true })
    } else {
      await fs.promises.rm(path.join(LOCAL_DIR, key), { force: true })
    }
  } catch (error) {
    console.error('[storage] Failed to delete image:', key, error.message)
  }
}
